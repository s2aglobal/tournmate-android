/** Score actions the match cards and draw views can trigger. */
internal class MatchActions(
    val isCreator: Boolean,
    val uid: String?,
    val onEnterSetScore: (Match) -> Unit,
    val onEnterSimpleScore: (Match) -> Unit,
    val onConfirm: (Match) -> Unit,
    val onDispute: (Match) -> Unit,
    val onResolveDispute: (Match) -> Unit,
    val onEditSetScore: (Match) -> Unit,
    val onEditSimpleScore: (Match) -> Unit,
    /** Opens the "Review Submitted Score" confirm / dispute dialog (iOS `matchForReview`). */
    val onReview: (Match) -> Unit,
) {
    fun isMine(match: Match): Boolean = uid != null && match.isParticipant(uid)

    fun canConfirm(match: Match): Boolean = (isMine(match) && match.submittedBy != uid) || isCreator

    /** Tap on a draw / bracket card. */
    fun onDrawTap(match: Match) {
        when (match.status) {
            MatchStatus.SCHEDULED -> if (isCreator || isMine(match)) onEnterSetScore(match)
            MatchStatus.SCORE_SUBMITTED -> if (canConfirm(match)) onReview(match)
            MatchStatus.DISPUTED -> if (isCreator) onResolveDispute(match)
            MatchStatus.FINISHED -> if (isCreator) onEditSetScore(match)
        }
    }
}

private enum class MatchSubTab { DRAW, MATCHES, STANDINGS }

private val MatchFormat.isElimination: Boolean
    get() = this == MatchFormat.SINGLE_ELIMINATION || this == MatchFormat.DOUBLE_ELIMINATION

@Composable
internal fun MatchesTabContent(
    state: TournamentDetailUiState,
    viewModel: TournamentDetailViewModel,
    actions: MatchActions,
) {
    val tournament = state.tournament ?: return
    var subTab by remember { mutableStateOf(MatchSubTab.DRAW) }
    var selectedRound by remember { mutableStateOf<Int?>(null) }
    val context = LocalContext.current

    if (state.matches.isEmpty()) {
        Column(
            Modifier.fillMaxWidth().padding(40.dp),
            horizontalAlignment = Alignment.CenterHorizontally,
            verticalArrangement = Arrangement.spacedBy(16.dp),
        ) {
            Icon(Icons.Outlined.Stadium, null, Modifier.size(48.dp), tint = Color.Gray.copy(alpha = 0.3f))
            Text("No matches yet", fontSize = 16.sp, fontWeight = FontWeight.Bold, color = Color.Gray)
            Text(
                "Matches will appear here once they are generated by the organizer.",
                fontSize = 12.sp, color = Color.Gray, textAlign = TextAlign.Center,
            )
        }
        return
    }

    val drawLabel = if (tournament.matchFormat.isElimination) "Bracket" else "Draw"

    Column(Modifier.fillMaxWidth()) {
        // Sub-tab segment (capsule, Play-tab style) with the PDF button beside it.
        // Bottom gap matches the 24dp above (tab picker 4 + content 20), like iOS.
        Row(
            Modifier.fillMaxWidth().padding(bottom = 24.dp),
            verticalAlignment = Alignment.CenterVertically,
            horizontalArrangement = Arrangement.spacedBy(10.dp),
        ) {
            Row(
                Modifier.weight(1f).clip(CircleShape).background(SegmentTrack)
                    .border(1.dp, Color.Gray.copy(alpha = 0.12f), CircleShape).padding(4.dp),
            ) {
                SubTabButton(drawLabel, subTab == MatchSubTab.DRAW, Modifier.weight(1f)) { subTab = MatchSubTab.DRAW }
                SubTabButton("Matches", subTab == MatchSubTab.MATCHES, Modifier.weight(1f)) { subTab = MatchSubTab.MATCHES }
                SubTabButton("Standings", subTab == MatchSubTab.STANDINGS, Modifier.weight(1f)) { subTab = MatchSubTab.STANDINGS }
            }
            Box {
                var showPdfMenu by remember { mutableStateOf(false) }
                val tabName = when (subTab) {
                    MatchSubTab.DRAW -> drawLabel
                    MatchSubTab.MATCHES -> "Matches"
                    MatchSubTab.STANDINGS -> "Standings"
                }
                fun pdfInput() = TournamentPdfExporter.Input(
                    tournament = tournament,
                    matches = state.matches,
                    registrations = state.registrations,
                    totalBracketRounds = state.totalBracketRounds,
                    rrStandings = viewModel.computeRRStandings(state),
                    groupStandings = viewModel.computeGroupStandings(state),
                    bracketProgress = viewModel.computeBracketProgress(state),
                    rrTieBreakCaption = StandingsEntry.tieBreakCaption(viewModel.standingsTieBreaker(state), tournament.sportType),
                    groupTieBreakCaption = StandingsEntry.tieBreakCaption(viewModel.groupStandingsTieBreaker(state), tournament.sportType),
                )
                Row(
                    Modifier.height(44.dp).clip(CircleShape).background(AppAccent.copy(alpha = 0.1f))
                        .clickable { showPdfMenu = true }
                        .padding(horizontal = 14.dp),
                    verticalAlignment = Alignment.CenterVertically,
                    horizontalArrangement = Arrangement.spacedBy(5.dp),
                ) {
                    Icon(Icons.Default.Description, null, Modifier.size(12.dp), tint = AppAccent)
                    Text("PDF", fontSize = 11.sp, fontWeight = FontWeight.Bold, color = AppAccent)
                }
                DropdownMenu(expanded = showPdfMenu, onDismissRequest = { showPdfMenu = false }) {
                    DropdownMenuItem(
                        text = { Text("Share PDF") },
                        leadingIcon = { Icon(Icons.Default.Share, null) },
                        onClick = {
                            showPdfMenu = false
                            TournamentPdfExporter.share(context, pdfInput(), tabName)
                        },
                    )
                    DropdownMenuItem(
                        text = { Text("Print") },
                        leadingIcon = { Icon(Icons.Default.Print, null) },
                        onClick = {
                            showPdfMenu = false
                            TournamentPdfExporter.print(context, pdfInput(), tabName)
                        },
                    )
                }
            }
        }

        when (subTab) {
            MatchSubTab.DRAW -> DrawContent(state, viewModel, actions)
            MatchSubTab.MATCHES -> when (tournament.matchFormat) {
                MatchFormat.SINGLE_ELIMINATION, MatchFormat.DOUBLE_ELIMINATION ->
                    BracketMatchesContent(state, actions, selectedRound) { selectedRound = it }
                MatchFormat.GROUP_KNOCKOUT -> GroupKnockoutMatchesContent(state, actions)
                else -> RoundRobinMatchesContent(state, actions, selectedRound) { selectedRound = it }
            }
            MatchSubTab.STANDINGS -> StandingsContent(state, viewModel)
        }
    }
}

