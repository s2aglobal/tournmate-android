@Composable
private fun BracketMatchCard(match: Match, actions: MatchActions) {
    val mine = actions.isMine(match)
    MatchCardShell(mine, if (mine) AppAccent else Indigo, 12.dp) {
        Row(verticalAlignment = Alignment.CenterVertically, horizontalArrangement = Arrangement.spacedBy(8.dp)) {
            Text("MATCH #${match.bracketPosition?.let { "${it + 1}" } ?: "?"}", fontSize = 10.sp, fontWeight = FontWeight.Bold, color = Color.Gray)
            if (mine) YourMatchBadge()
            Spacer(Modifier.weight(1f))
            Text(
                matchStatusText(match).uppercase(), fontSize = 10.sp, fontWeight = FontWeight.Bold,
                color = if (match.status == MatchStatus.FINISHED) AppAccent else Indigo,
            )
        }
        Row(verticalAlignment = Alignment.CenterVertically) {
            TeamBracketLabel(registrationShortName(match.teamA), isRight = false, Modifier.weight(1f))
            Text("VS", fontSize = 10.sp, fontWeight = FontWeight.Bold, color = Color.Gray.copy(alpha = 0.3f), modifier = Modifier.padding(horizontal = 8.dp))
            TeamBracketLabel(registrationShortName(match.teamB), isRight = true, Modifier.weight(1f))
        }
        if (match.status == MatchStatus.FINISHED) {
            Text(iosScoreLine(match), fontSize = 12.sp, fontWeight = FontWeight.Bold, color = AppAccent, textAlign = TextAlign.Center, modifier = Modifier.fillMaxWidth())
        }
        BracketMatchActions(match, actions)
    }
}

@Composable
