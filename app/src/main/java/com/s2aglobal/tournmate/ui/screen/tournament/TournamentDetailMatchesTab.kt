@Composable
private fun DrawContent(state: TournamentDetailUiState, viewModel: TournamentDetailViewModel, actions: MatchActions) {
    val tournament = state.tournament ?: return
    val rounds = state.allMatchesByRound
    val tap: (Match) -> Unit = { actions.onDrawTap(it) }
    when (tournament.matchFormat) {
        MatchFormat.SINGLE_ELIMINATION -> BracketDrawView(rounds, state.totalBracketRounds, tap)
        MatchFormat.DOUBLE_ELIMINATION -> DoubleEliminationDrawView(rounds, state.totalBracketRounds, tap)
        MatchFormat.GROUP_KNOCKOUT -> GroupKnockoutDrawView(rounds, state.totalBracketRounds, tap)
        MatchFormat.SWISS -> SwissDrawView(
            rounds = rounds,
            currentSwissRound = state.currentSwissRound,
            isOrganizer = state.isCreator,
            canGenerateNextRound = !state.isSwissComplete,
            isLoading = state.isLoading,
            onTapMatch = tap,
            onGenerateNextRound = { viewModel.generateNextSwissRound() },
        )
        MatchFormat.MANUAL_DRAW -> ManualDrawView(rounds, state.formedTeams, tap)
        MatchFormat.ROUND_ROBIN -> RoundRobinDrawView(rounds, tournament.formatConfig.pointsPerWin, tournament.formatConfig.pointsPerLoss, tap)
    }
}

