@Composable
private fun ConfirmDisputeRow(match: Match, actions: MatchActions) {
    if (!actions.canConfirm(match)) return
    Row(horizontalArrangement = Arrangement.spacedBy(12.dp)) {
        ActionLink("CONFIRM", AppAccent) { actions.onConfirm(match) }
        ActionLink("DISPUTE", Color.Red) { actions.onDispute(match) }
    }
}

@Composable
private fun BracketMatchActions(match: Match, actions: MatchActions) {
    when (match.status) {
        MatchStatus.SCHEDULED -> if (actions.isCreator || actions.isMine(match)) {
            ActionLink("ENTER SCORE", AppAccent, Icons.Default.EditNote) { actions.onEnterSetScore(match) }
        }
        MatchStatus.SCORE_SUBMITTED -> ConfirmDisputeRow(match, actions)
        MatchStatus.DISPUTED -> if (actions.isCreator) {
            ActionLink("RESOLVE DISPUTE", WarningOrange, Icons.Outlined.WarningAmber) { actions.onResolveDispute(match) }
        }
        MatchStatus.FINISHED -> if (actions.isCreator) {
            ActionLink("EDIT SCORE", Color.Gray, Icons.Default.EditNote) { actions.onEditSetScore(match) }
        }
    }
}

@Composable
private fun RoundRobinMatchCard(match: Match, actions: MatchActions) {
    val mine = actions.isMine(match)
    MatchCardShell(mine, AppAccent, 8.dp) {
        Row(verticalAlignment = Alignment.CenterVertically, horizontalArrangement = Arrangement.spacedBy(8.dp)) {
            Text(
                "${registrationFullName(match.teamA)} vs ${registrationFullName(match.teamB)}".uppercase(),
                fontSize = 10.sp, fontWeight = FontWeight.Bold, color = Color.Gray,
                maxLines = 1, overflow = TextOverflow.Ellipsis, modifier = Modifier.weight(1f, fill = false),
            )
            if (mine) YourMatchBadge()
            Spacer(Modifier.weight(1f))
            Text(
                matchStatusText(match).uppercase(), fontSize = 10.sp, fontWeight = FontWeight.Bold,
                color = if (match.status == MatchStatus.FINISHED) AppAccent else WarningOrange,
            )
        }
        Text(iosScoreLine(match), fontSize = 14.sp, fontWeight = FontWeight.Bold, color = if (match.status == MatchStatus.FINISHED) AppAccent else Color.Black)

        when (match.status) {
            MatchStatus.SCHEDULED -> if (actions.isCreator || mine) {
                ActionLink("ENTER SCORE", AppAccent, Icons.Default.EditNote) { actions.onEnterSimpleScore(match) }
            }
            MatchStatus.SCORE_SUBMITTED -> ConfirmDisputeRow(match, actions)
            MatchStatus.DISPUTED -> if (actions.isCreator) {
                ActionLink("RESOLVE DISPUTE", WarningOrange, Icons.Outlined.WarningAmber) { actions.onResolveDispute(match) }
            }
            MatchStatus.FINISHED -> Row(verticalAlignment = Alignment.CenterVertically, horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                match.winnerRegistration?.let { winner ->
                    Row(verticalAlignment = Alignment.CenterVertically, horizontalArrangement = Arrangement.spacedBy(4.dp)) {
                        Icon(Icons.Default.CheckCircle, null, Modifier.size(12.dp), tint = AppAccent)
                        Text("Winner: ${registrationShortName(winner)}", fontSize = 12.sp, fontWeight = FontWeight.Bold, color = AppAccent)
                    }
                }
                if (actions.isCreator) {
                    Spacer(Modifier.weight(1f))
                    ActionLink("EDIT", Color.Gray, Icons.Default.EditNote) { actions.onEditSimpleScore(match) }
                }
            }
        }
    }
}

// ── Standings ────────────────────────────────────────

@Composable
private fun StandingsContent(state: TournamentDetailUiState, viewModel: TournamentDetailViewModel) {
    val tournament = state.tournament ?: return
    when (tournament.matchFormat) {
        MatchFormat.SINGLE_ELIMINATION, MatchFormat.DOUBLE_ELIMINATION -> BracketStandingsTable(viewModel.computeBracketProgress(state), state.totalBracketRounds)
        MatchFormat.GROUP_KNOCKOUT -> {
            val groups = viewModel.computeGroupStandings(state)
            if (groups.isEmpty()) {
                EmptyStandings("Standings will appear once group matches are completed.")
            } else {
                Column(verticalArrangement = Arrangement.spacedBy(20.dp)) {
                    val advancing = tournament.formatConfig.advancingPerGroup
                    groups.keys.sorted().forEach { group ->
                        Column(verticalArrangement = Arrangement.spacedBy(8.dp)) {
                            Text("GROUP $group", fontSize = 12.sp, fontWeight = FontWeight.ExtraBold, letterSpacing = 2.sp, color = AppAccent)
                            GroupStandingsTable(groups[group].orEmpty(), advancing, tournament.sportType.ranksStandingsBySets)
                        }
                    }
                    if (state.hasKnockoutMatches) BracketStandingsTable(viewModel.computeBracketProgress(state), state.totalBracketRounds)
                }
            }
        }
        else -> RoundRobinStandingsTable(viewModel.computeRRStandings(state), tournament.sportType.ranksStandingsBySets)
    }
}

