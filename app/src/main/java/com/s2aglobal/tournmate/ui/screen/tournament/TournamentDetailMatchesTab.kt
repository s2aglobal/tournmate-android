@Composable
private fun RoundChips(labels: List<Pair<Int, String>>, active: Int, onSelect: (Int) -> Unit) {
    Row(Modifier.horizontalScroll(rememberScrollState()), horizontalArrangement = Arrangement.spacedBy(8.dp)) {
        labels.forEach { (round, label) ->
            val isActive = round == active
            Text(
                label, fontSize = 12.sp, fontWeight = FontWeight.Bold,
                color = if (isActive) Color.White else Color.Gray,
                modifier = Modifier.clip(RoundedCornerShape(20.dp))
                    .background(if (isActive) AppAccent else Color.Gray.copy(alpha = 0.1f))
                    .clickable { onSelect(round) }
                    .padding(horizontal = 16.dp, vertical = 8.dp),
            )
        }
    }
}

@Composable
private fun BracketMatchesContent(state: TournamentDetailUiState, actions: MatchActions, selected: Int?, onSelect: (Int) -> Unit) {
    val rounds = state.allMatchesByRound
    val active = selected?.takeIf { s -> rounds.any { it.round == s } } ?: rounds.lastOrNull()?.round ?: 1
    Column(verticalArrangement = Arrangement.spacedBy(20.dp)) {
        RoundChips(rounds.map { it.round to Match.bracketRoundName(it.round, state.totalBracketRounds) }, active, onSelect)

        if (active == 1 && rounds.firstOrNull()?.round == 1) {
            val byes = state.byeTeamNames
            if (byes.isNotEmpty()) {
                Column(
                    Modifier.fillMaxWidth().clip(RoundedCornerShape(14.dp)).background(AppAccent.copy(alpha = 0.06f)).padding(14.dp),
                    verticalArrangement = Arrangement.spacedBy(8.dp),
                ) {
                    Row(verticalAlignment = Alignment.CenterVertically, horizontalArrangement = Arrangement.spacedBy(6.dp)) {
                        Icon(Icons.Default.ArrowCircleRight, null, Modifier.size(14.dp), tint = AppAccent)
                        Text("${byes.size} team${if (byes.size == 1) "" else "s"} advance with a bye", fontSize = 13.sp, fontWeight = FontWeight.Bold, color = AppAccent)
                    }
                    byes.forEach { Text("• $it", fontSize = 12.sp, color = Color.Gray) }
                }
            }
        }

        rounds.firstOrNull { it.round == active }?.let { group ->
            Column(verticalArrangement = Arrangement.spacedBy(16.dp)) {
                group.matches.forEach { BracketMatchCard(it, actions) }
            }
        }
    }
}

@Composable
private fun RoundRobinMatchesContent(state: TournamentDetailUiState, actions: MatchActions, selected: Int?, onSelect: (Int) -> Unit) {
    val grouped = state.matches.groupBy { it.round ?: 0 }
    val sortedRounds = grouped.keys.sorted()
    val active = selected?.takeIf { it in grouped } ?: sortedRounds.firstOrNull() ?: 1
    Column(verticalArrangement = Arrangement.spacedBy(20.dp)) {
        RoundChips(sortedRounds.map { it to "Round $it" }, active, onSelect)
        grouped[active]?.let { matches ->
            Column(verticalArrangement = Arrangement.spacedBy(12.dp)) {
                matches.forEach { RoundRobinMatchCard(it, actions) }
            }
        }
    }
}

@Composable
private fun StageLabel(text: String, color: Color) {
    Text(
        text, fontSize = 12.sp, fontWeight = FontWeight.ExtraBold, letterSpacing = 2.sp, color = color,
        modifier = Modifier.clip(RoundedCornerShape(8.dp)).background(color.copy(alpha = 0.08f)).padding(horizontal = 12.dp, vertical = 6.dp),
    )
}

@Composable
private fun GroupKnockoutMatchesContent(state: TournamentDetailUiState, actions: MatchActions) {
    val groupMatches = state.matches.filter { it.groupLabel != null }
    val knockout = state.matches.filter { it.groupLabel == null }
    Column(verticalArrangement = Arrangement.spacedBy(20.dp)) {
        groupMatches.groupBy { it.groupLabel ?: "?" }.toSortedMap().forEach { (group, matches) ->
            Column(verticalArrangement = Arrangement.spacedBy(12.dp)) {
                StageLabel("GROUP $group", AppAccent)
                matches.forEach { RoundRobinMatchCard(it, actions) }
            }
        }
        if (knockout.isNotEmpty()) {
            Column(verticalArrangement = Arrangement.spacedBy(12.dp)) {
                StageLabel("KNOCKOUT STAGE", WarningOrange)
                knockout.groupBy { it.round ?: 0 }.toSortedMap().values.forEach { roundMatches ->
                    roundMatches.forEach { RoundRobinMatchCard(it, actions) }
                }
            }
        }
    }
}

private fun matchStatusText(match: Match): String = when (match.status) {
    MatchStatus.FINISHED -> "Completed"
    MatchStatus.SCORE_SUBMITTED -> "Pending Confirm"
    MatchStatus.DISPUTED -> "Disputed"
    MatchStatus.SCHEDULED -> "Upcoming"
}

/** iOS `Match.displayScoreLine`. */
internal fun iosScoreLine(match: Match): String {
    match.cricketScoreLine?.let { return it }
    if (match.setScores.isNotEmpty()) {
        val sets = match.setScores.joinToString(", ") { "${it.teamAPoints}-${it.teamBPoints}" }
        return "$sets (${match.setsWonByA}-${match.setsWonByB})"
    }
    val a = match.scoreA
    val b = match.scoreB
    if (a == null || b == null) {
        return when (match.status) {
            MatchStatus.SCORE_SUBMITTED -> "Awaiting Confirmation"
            MatchStatus.DISPUTED -> "Score Disputed ⚠️"
            MatchStatus.FINISHED -> "Finished"
            MatchStatus.SCHEDULED -> "Scheduled"
        }
    }
    return "$a - $b"
}

